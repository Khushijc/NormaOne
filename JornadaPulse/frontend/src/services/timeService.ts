/**
 * Clocking (TIM-02) — future endpoint: POST /companies/{c}/employees/me/events with an
 * Idempotency-Key header. A success is reported only after the event is persisted; the
 * response carries a durable receipt. A connectivity failure records nothing and shows
 * "No registrado" with the documented correction fallback (BRD §09).
 */
import { index } from '../domain/indexes';
import { newId, receiptFor } from '../domain/ids';
import { BusinessRuleError, NotFoundError } from '../domain/permissions';
import { effectiveValues, relationshipOn, sessionState, type SessionState } from '../domain/records';
import { localDate, nowInstant } from '../domain/time';
import type { AttendanceEvent, BreakKind, EventType, FailedAttempt, ID, RetentionDecision, WorkMode, WorkSession } from '../domain/types';
import { getDemoSwitches, transact } from '../store/db';
import { getCtx, latency, ownCompany, requirePerm, type Ctx } from './context';

export interface MyStatus {
  state: 'not_started' | SessionState;
  session: WorkSession | null;
  /** Older open session that was never closed (shown as "incompleto", not auto-completed). */
  staleSession: WorkSession | null;
}

/** Current state of the caller's working day. */
export function myStatus(ctx: Ctx = getCtx()): MyStatus {
  if (!ctx.employee) return { state: 'not_started', session: null, staleSession: null };
  const mine = (index(ctx.db).sessionsByEmployee.get(ctx.employee.id) ?? []).slice().sort((a, b) => b.createdAt.localeCompare(a.createdAt));
  let stale: WorkSession | null = null;
  for (const s of mine) {
    const v = effectiveValues(ctx.db, s);
    if (v.end) continue;
    const st = sessionState(ctx.db, s);
    if (st === 'incomplete') {
      stale ??= s;
      continue;
    }
    return { state: st, session: s, staleSession: stale };
  }
  const todays = mine.find((s) => s.date === ctx.today && effectiveValues(ctx.db, s).end);
  return { state: todays ? 'complete' : 'not_started', session: todays ?? null, staleSession: stale };
}

export class NotRecordedError extends Error {
  failedAttemptId: ID;
  constructor(failedAttemptId: ID) {
    super('No registrado: no se ha podido guardar el fichaje (fallo de conexión simulado). Anote la hora y solicite una corrección.');
    this.name = 'NotRecordedError';
    this.failedAttemptId = failedAttemptId;
  }
}

export interface ClockInput {
  action: EventType;
  worksiteId: ID;
  mode: WorkMode;
  breakKind?: BreakKind;
  /** Generated by the UI once per user intent; repeated submissions return the same event. */
  idempotencyKey: string;
}

export interface ClockResult {
  event: AttendanceEvent;
  session: WorkSession;
  receipt: string;
  /** True when the key had already been processed (no duplicate was created). */
  duplicate: boolean;
}

export async function clock(input: ClockInput): Promise<ClockResult> {
  await latency(350);
  const ctx = getCtx();
  requirePerm(ctx, 'time.clock_own');
  const emp = ctx.employee;
  if (!emp || emp.status !== 'active') throw new BusinessRuleError('Su ficha de empleado no está activa en esta empresa.');

  // Idempotency: the same key never produces a second event.
  const existing = ctx.db.events.find((e) => e.companyId === ctx.company.id && e.employeeId === emp.id && e.idempotencyKey === input.idempotencyKey);
  if (existing) {
    const session = ctx.db.sessions.find((s) => s.id === existing.sessionId)!;
    return { event: existing, session, receipt: existing.receipt, duplicate: true };
  }

  if (!emp.worksiteIds.includes(input.worksiteId)) throw new BusinessRuleError('El centro seleccionado no está asignado a su ficha.');
  const rel = relationshipOn(ctx.db, emp.id, ctx.today);
  if (input.mode === 'remote' && !rel?.remoteAllowed) throw new BusinessRuleError('Su relación laboral no tiene autorizado el trabajo a distancia.');

  const status = myStatus(ctx);
  const at = nowInstant();
  const check = (): void => {
    switch (input.action) {
      case 'clock_in':
        if (status.state === 'working' || status.state === 'on_break') throw new BusinessRuleError('Ya hay una jornada abierta: registre la salida antes de una nueva entrada.');
        return;
      case 'clock_out':
        if (status.state === 'on_break') throw new BusinessRuleError('Está en pausa: registre el fin de la pausa antes de la salida.');
        if (status.state !== 'working') throw new BusinessRuleError('No hay ninguna jornada abierta: no se puede registrar la salida.');
        return;
      case 'break_start':
        if (status.state !== 'working') throw new BusinessRuleError('Solo puede iniciar una pausa durante una jornada abierta.');
        return;
      case 'break_end':
        if (status.state !== 'on_break') throw new BusinessRuleError('No hay ninguna pausa iniciada.');
        return;
    }
  };
  check();

  // Simulated connectivity failure: nothing is recorded; the attempt is logged for the correction route.
  if (getDemoSwitches().simulateClockFailure) {
    const failed: FailedAttempt = { id: newId('fat'), companyId: ctx.company.id, employeeId: emp.id, action: input.action, attemptedAt: at, worksiteId: input.worksiteId, reason: 'Sin conexión con el servidor (simulación).', correctionId: null };
    transact(ctx.actor, ctx.company.id, (tx) => {
      tx.insert('failedAttempts', failed);
      tx.audit({ action: 'time.not_recorded', entityType: 'failed_attempt', entityId: failed.id, entityLabel: `${emp.firstName} ${emp.lastName}`, employeeId: emp.id, summary: 'Intento de fichaje no registrado (fallo de conexión simulado).' });
    });
    throw new NotRecordedError(failed.id);
  }

  return transact(ctx.actor, ctx.company.id, (tx) => {
    const eventId = newId('evt');
    let session: WorkSession;
    if (input.action === 'clock_in') {
      session = {
        id: newId('ses'),
        companyId: ctx.company.id,
        employeeId: emp.id,
        worksiteId: input.worksiteId,
        timezone: ctx.company.timezone,
        mode: input.mode,
        date: localDate(at, ctx.company.timezone),
        startEventId: eventId,
        endEventId: null,
        breaks: [],
        correctionIds: [],
        origin: 'clocked',
        createdAt: at,
        updatedAt: at,
      };
      tx.insert('sessions', session);
    } else {
      session = tx.get('sessions', status.session!.id)!;
    }
    const event: AttendanceEvent = {
      id: eventId,
      companyId: ctx.company.id,
      employeeId: emp.id,
      sessionId: session.id,
      type: input.action,
      at,
      receivedAt: nowInstant(),
      timezone: ctx.company.timezone,
      source: 'web',
      worksiteId: input.action === 'clock_in' ? input.worksiteId : session.worksiteId,
      mode: input.mode,
      breakKind: input.action === 'break_start' || input.action === 'break_end' ? input.breakKind ?? 'rest' : null,
      idempotencyKey: input.idempotencyKey,
      receipt: receiptFor(eventId),
      recordedBy: ctx.user.id,
      correctionId: null,
    };
    tx.insert('events', event);
    if (input.action === 'clock_out') {
      session = tx.update('sessions', session.id, { endEventId: event.id, updatedAt: at });
    } else if (input.action === 'break_start') {
      session = tx.update('sessions', session.id, (s) => ({ breaks: [...s.breaks, { id: newId('brk'), startEventId: event.id, endEventId: null, kind: event.breakKind! }], updatedAt: at }));
    } else if (input.action === 'break_end') {
      session = tx.update('sessions', session.id, (s) => ({ breaks: s.breaks.map((b) => (b.endEventId ? b : { ...b, endEventId: event.id })), updatedAt: at }));
    }
    tx.audit({ action: `time.${input.action}`, entityType: 'event', entityId: event.id, entityLabel: `${emp.firstName} ${emp.lastName}`, employeeId: emp.id, summary: `Recibo ${event.receipt}.` });
    return { event, session, receipt: event.receipt, duplicate: false };
  });
}

/** Retention period end for a time record: four years after the working day (ET art. 34.9; TIM-07). */
export function retentionUntil(date: string): string {
  const [y, m, d] = date.split('-').map(Number);
  return `${y + 4}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
}

/**
 * AC-TIM-04: an attempt to delete a time record inside its retention period is blocked and
 * the decision is recorded. The prototype never deletes time records.
 */
export async function requestRecordDeletion(sessionId: ID, reason: string): Promise<RetentionDecision> {
  await latency();
  const ctx = getCtx();
  requirePerm(ctx, 'records.delete_request');
  const s = ownCompany(ctx, ctx.db.sessions.find((x) => x.id === sessionId));
  if (!reason.trim()) throw new BusinessRuleError('Indique el motivo de la solicitud de eliminación.');
  const until = retentionUntil(s.date);
  const blocked = ctx.today <= until;
  const decision: RetentionDecision = {
    id: newId('ret'),
    companyId: ctx.company.id,
    entityType: 'session',
    entityId: s.id,
    requestedBy: ctx.user.id,
    requestedAt: nowInstant(),
    outcome: blocked ? 'blocked' : 'allowed',
    retentionUntil: until,
    reason: reason.trim(),
  };
  const emp = ctx.db.employees.find((e) => e.id === s.employeeId);
  transact(ctx.actor, ctx.company.id, (tx) => {
    tx.insert('retentionDecisions', decision);
    tx.audit({
      action: 'retention.delete_blocked',
      entityType: 'session',
      entityId: s.id,
      entityLabel: emp ? `${emp.firstName} ${emp.lastName} · ${s.date}` : s.date,
      employeeId: s.employeeId,
      summary: blocked ? `Eliminación bloqueada: el registro debe conservarse hasta el ${until}.` : 'Plazo de conservación cumplido: la eliminación requiere revisión y no se ejecuta en el prototipo.',
      reason: reason.trim(),
    });
  });
  return decision;
}

/** Looks up a session in the active company (throws NotFound across companies). */
export function getSession(ctx: Ctx, id: ID): WorkSession {
  const s = ctx.db.sessions.find((x) => x.id === id);
  if (!s || s.companyId !== ctx.company.id) throw new NotFoundError();
  return s;
}

export function failedAttemptsFor(ctx: Ctx, employeeId: ID): FailedAttempt[] {
  return ctx.db.failedAttempts.filter((f) => f.companyId === ctx.company.id && f.employeeId === employeeId).sort((a, b) => b.attemptedAt.localeCompare(a.attemptedAt));
}

